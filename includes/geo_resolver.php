if (!function_exists('resolveIpLocationFast')) {
function resolveIpLocationFast($ip, $pdo = null) {
    if (empty($ip) || $ip === '127.0.0.1' || strpos($ip, '192.168.') === 0 || strpos($ip, '10.') === 0) {
        return null;
    }
    if ($pdo) {
        try {
            $stmt = $pdo->prepare("SELECT city, state FROM gcm_ip_geo_cache WHERE ip = ? LIMIT 1");
            $stmt->execute([$ip]);
            $cached = $stmt->fetch(PDO::FETCH_ASSOC);
            if ($cached) return $cached;
        } catch (\Exception $e) {}
    }
    $ch = curl_init("http://ip-api.com/json/" . urlencode($ip) . "?fields=status,country,regionName,city");
    curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
    curl_setopt($ch, CURLOPT_TIMEOUT, 1);
    curl_setopt($ch, CURLOPT_CONNECTTIMEOUT, 1);
    $res = curl_exec($ch);
    curl_close($ch);
    if ($res) {
        $data = json_decode($res, true);
        if (($data['status'] ?? '') === 'success' && !empty($data['city'])) {
            $city = trim($data['city']);
            $state = trim($data['regionName'] ?? '');
            if ($pdo) {
                try {
                    $stmtIns = $pdo->prepare("INSERT IGNORE INTO gcm_ip_geo_cache (ip, city, state) VALUES (?, ?, ?)");
                    $stmtIns->execute([$ip, $city, $state]);
                } catch (\Exception $e) {}
            }
            return ['city' => $city, 'state' => $state];
        }
    }
    return null;
}
